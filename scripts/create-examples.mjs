import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createScore,makeNote,toMusicXML,toMidi,validateScore} from '../src/model.js';
import {instrumentById,makePart,INSTRUMENTS} from '../src/instruments.js';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const score=createScore({title:'Estudio para barítono',composer:'Voz y piano · ejemplo de Partitura',measures:8});
score.tempo=92;
const voice=makePart(instrumentById('voice-baritone'),8);
const melody=[[48,52,55,52],[50,53,57,53],[52,55,60,55],[50,53,59,55],[48,52,55,60],[57,53,50,53],[55,59,62,59],[60]];
const words=['Can','to','a','la','luz','de','la','ma','ña','na'];let syllable=0;
voice.measures.forEach((m,i)=>{m.notes=melody[i].map(p=>{const n=makeNote(p,i===7?4:1);n.lyric=words[syllable++%words.length];return n;});});
voice.measures[0].notes[0].dynamic='mp';voice.measures[0].notes[0].chord='C';voice.measures[1].notes[0].chord='Dm';voice.measures[6].notes[0].chord='G7';voice.measures[7].notes[0].chord='C';
const roots=[48,50,48,43,48,41,43,48];
score.parts[0].name='Piano · mano derecha';
score.parts.forEach((p,pi)=>p.measures.forEach((m,i)=>{const r=roots[i]+(pi? -12:12),n=makeNote(r,4);n.pitches=pi?[r,r+7]:[r,r+(i===1||i===5?3:4),r+7];m.notes=[n];}));
score.parts.unshift(voice);validateScore(score);
const out=path.join(root,'Ejemplos');fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'Baritono-y-piano.partitura'),JSON.stringify(score,null,2));
fs.writeFileSync(path.join(out,'Baritono-y-piano.musicxml'),toMusicXML(score));
fs.writeFileSync(path.join(out,'Baritono-y-piano.mid'),toMidi(score));
fs.writeFileSync(path.join(root,'catalogo-instrumentos.json'),JSON.stringify(INSTRUMENTS,null,2));
console.log('Ejemplo de barítono y piano y catálogo de '+INSTRUMENTS.length+' instrumentos creados.');
